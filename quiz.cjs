const questions = groups.flatMap(([goal, items], g) => items.map(([prompt, options, answer, explanation], i) => ({ id: `g${g + 1}q${i + 1}`, goal, prompt, options, answer, explanation })));
const PER_GOAL = 4;
function pickQuestions() {
  return groups.flatMap((_, g) => questions.filter(q => q.id.startsWith(`g${g + 1}q`))
    .map(q => ({ q, n: crypto.randomInt(0, 1e9) })).sort((a, b) => a.n - b.n).slice(0, PER_GOAL).map(v => v.q));
}
function publicQuestion(q) { return { id: q.id, goal: q.goal, prompt: q.prompt, options: q.options }; }
module.exports = { questions, groups: groups.map(([goal]) => goal), pickQuestions, publicQuestion, PER_GOAL };
